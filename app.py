# Importer Gradio et charger les éléments sauvegardés
import gradio as gr
import joblib
import numpy as np
import pandas as pd

best_model = joblib.load('best_model.joblib')
scaler = joblib.load('scaler.joblib')
encoders = joblib.load('encoders.joblib')

if isinstance(encoders, list):
    cat_cols = ['Fuel_Type', 'Seller_Type', 'Transmission']
    encoders = dict(zip(cat_cols, encoders))
feature_cols = ['Kms_Driven', 'Present_Price', 'Fuel_Type', 'Seller_Type', 'Transmission', 'Age']


# Fonction de prédiction utilisée par Gradio (prédiction simple)
def Pred_func(kms_driven, present_price, fuel_type, seller_type, transmission, age):
    # Encoder les variables catégorielles avec les mêmes encodeurs qu'à l'entraînement
    fuel_enc = encoders['Fuel_Type'].transform([fuel_type])[0]
    seller_enc = encoders['Seller_Type'].transform([seller_type])[0]
    trans_enc = encoders['Transmission'].transform([transmission])[0]

    # Construire les variables dans le même ordre que pendant l'entraînement
    x_new = np.array([[
        kms_driven,
        present_price,
        fuel_enc,
        seller_enc,
        trans_enc,
        age
    ]], dtype=float)


    # Prédiction du prix de vente
    prediction = best_model.predict(x_new)[0]
    return round(float(prediction), 2)

# Fonction de prédiction multiple à partir d'un fichier CSV
def Pred_func_csv(file):
    df_in = pd.read_csv(file)
    predictions = []
    for _, row in df_in.iterrows():
        y_pred = Pred_func(
            row['Kms_Driven'],
            row['Present_Price'],
            row['Fuel_Type'],
            row['Seller_Type'],
            row['Transmission'],
            row['Age']
        )
        predictions.append(y_pred)
    df_in['Predicted Selling_Price'] = predictions
    df_in.to_csv('predictions.csv', index=False)
    return 'predictions.csv'
